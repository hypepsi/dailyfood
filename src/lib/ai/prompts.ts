/** 在提示词末尾附上用户选择的估算风格；标准档不附加任何内容 */
export function withEstimateStyle(prompt: string, style: EstimateStyle): string {
  const extra = ESTIMATE_STYLE[style].prompt;
  return extra ? `${prompt}\n\n${extra}` : prompt;
}
